import { FileNode } from "../../types/FileTree";

/**
 * Рекурсивно собирает идентификаторы (ID) всех файлов внутри данного узла дерева и его дочерних узлов.
 * Если узел сам является файлом, возвращает его ID. Если узел - директория,
 * собирает ID из всех вложенных файлов.
 *
 * @param {FileNode} node - Узел дерева (файл или директория), с которого начинается сбор ID.
 * @returns {number[]} Массив числовых ID файлов, найденных в поддереве, начиная с `node`.
 *                     Возвращает пустой массив, если узел - пустая директория или не содержит файлов.
 */
export const collectFileIds = (node: FileNode): number[] => {
  // Базовый случай: узел является файлом с валидным ID
  if (!node.isDirectory && node.ID >= 0) {
    return [node.ID];
  }
  // Рекурсивный случай: узел является директорией с дочерними элементами
  if (node.children) {
    // Используем flatMap для объединения результатов рекурсивных вызовов
    return node.children.flatMap(collectFileIds);
  }
  // Базовый случай: узел - пустая директория или не содержит файлов
  return [];
};
